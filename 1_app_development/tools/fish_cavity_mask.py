"""스페셜 붕어빵 틀의 붕어빵 모양 격자 마스크 생성(24번 5단계, DEC-031·032).

fish/redbean.png의 불투명 부분(알파 > 128)을 틀 그림 좌표 (100, 66)에 놓고
WorkshopMoldArt.fishRect(215, 174 ~ 984, 706)를 16px 칸으로 나눈다. 칸 면적의
절반 이상이 붕어빵이면 마스크 칸이다. 결과는 lib/generated/fish_cavity_mask.dart.

실행(1_app_development에서): python tools/fish_cavity_mask.py [--check]
"""
import argparse
from pathlib import Path

import numpy as np
from PIL import Image

APP = Path(__file__).resolve().parents[1]
FISH = APP / 'assets/images/fish/redbean.png'
TARGET = APP / 'lib/generated/fish_cavity_mask.dart'
CANVAS = (1200, 880)
FISH_AT = (100, 66)
FISH_RECT = (215, 174, 984, 706)
CELL = 16


def render():
    fish = np.asarray(Image.open(FISH).convert('RGBA'))[..., 3] > 128
    canvas = np.zeros((CANVAS[1], CANVAS[0]), bool)
    x, y = FISH_AT
    canvas[y:y + fish.shape[0], x:x + fish.shape[1]] = fish
    left, top, right, bottom = FISH_RECT
    cols, rows = -(-(right - left) // CELL), -(-(bottom - top) // CELL)
    lines = []
    for r in range(rows):
        row = ''
        for c in range(cols):
            block = canvas[top + r * CELL:top + (r + 1) * CELL, left + c * CELL:left + (c + 1) * CELL]
            row += '#' if block.mean() >= .5 else '.'
        lines.append(row)
    count = sum(line.count('#') for line in lines)
    body = '\n'.join(f"  '{line}'," for line in lines)
    return (
        '// Generated by tools/fish_cavity_mask.py from assets/images/fish/redbean.png.\n'
        '// Do not edit by hand. One string per row, \'#\' = a cell of the fish cavity.\n\n'
        f'/// Cell size in mold-picture pixels; the grid starts at fishRect.topLeft.\n'
        f'const fishCavityCell = {CELL}.0;\n\n'
        '/// fishRect size in mold-picture pixels (the brush is a share of the width).\n'
        f'const fishCavityWidth = {right - left}.0;\n'
        f'const fishCavityHeight = {bottom - top}.0;\n\n'
        f'/// Number of \'#\' cells ({cols}x{rows} grid).\n'
        f'const fishCavityCount = {count};\n\n'
        f'const fishCavityRows = <String>[\n{body}\n];\n'), cols, rows, count


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text, cols, rows, count = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding='utf-8') != text:
            raise SystemExit('붕어빵 모양 마스크 생성물 불일치')
    else:
        TARGET.parent.mkdir(exist_ok=True)
        TARGET.write_text(text, encoding='utf-8', newline='\n')
    print(f'마스크 {cols}x{rows}칸, 붕어빵 칸 {count}개')


if __name__ == '__main__':
    main()
