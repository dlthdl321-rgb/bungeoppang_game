"""손님 콘텐츠 검증·Dart 문자열 생성. 앱/테스트 실행 도구가 아니다."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / '1_app_development/config/customer_content.json'
TARGET = ROOT / '1_app_development/lib/generated/customer_content.dart'
IDS = ['npc_' + name for name in ('yunha', 'doyun', 'makrye', 'seojin', 'taeo', 'eunchae', 'minjae', 'sua')]


def render():
    data = json.loads(SOURCE.read_text())
    assert data['schema'] == 1 and data['revision']
    assert [n['id'] for n in data['npcs']] == IDS
    dialogue_ids = set()
    for npc in data['npcs']:
        assert all(npc[k] for k in ('display_name', 'reference_name', 'appearance', 'personality'))
        assert len(npc['dialogues']) == 18
        for dialogue in npc['dialogues']:
            assert dialogue['id'] not in dialogue_ids and dialogue['text']
            assert dialogue['requires_context_qualification'] is True
            assert isinstance(dialogue['once_only'], bool)
            dialogue_ids.add(dialogue['id'])
    assert len(data['story_events']) == len(data['choice_events']) == 8
    assert {e['npc_id'] for e in data['choice_events']} == set(IDS)
    assert len({e['id'] for e in data['choice_events']}) == 8
    for event in data['choice_events']:
        assert event['eligibility_text'] and event['followup_text'] and event['prompt']
        assert [c['id'] for c in event['choices']] == ['a', 'b', 'c', 'wave']
        assert all(c['text'] and c['response'] for c in event['choices'])
    # Keep all numbers in development_balance.json, rather than in dialogue data.
    assert all('affinity' not in c for e in data['choice_events'] for c in e['choices'])
    text = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
    assert "'''" not in text
    return "// Generated by tools/customer_content.py; edit config/customer_content.json.\nconst workshopCustomerContentJson = r'''" + text + "''';\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != expected:
            raise SystemExit('손님 콘텐츠 생성물 불일치')
    else:
        TARGET.parent.mkdir(exist_ok=True)
        TARGET.write_text(expected)
    print('NPC8·대사144·관계8·선택8·생성물 정적 확인; 앱/테스트 실행 아님')


if __name__ == '__main__':
    main()
